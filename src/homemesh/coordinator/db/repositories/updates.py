"""Remote updates (``node_updates``): one row per ``update.apply`` job; the row id **is** the job id.

At most one row in the whole mesh is *active* (``requested`` / ``running``): :meth:`UpdateRepo.create_active`
checks and inserts inside one ``BEGIN IMMEDIATE`` transaction, and the partial unique index
``node_updates_one_active`` is the backstop. A final state clears ``active`` (NULL).

States: ``requested`` → ``running`` → a final run status (``ok``, ``ok_unconfirmed``, ``already_up_to_date``,
``rolled_back``, ``failed``, ``interrupted``), or the coordinator's own ``not_started`` / ``abandoned``.

**Guesses.** Three end states are the coordinator's verdict without word from the runner: ``not_started``,
``abandoned``, and ``failed`` set from the apply job (``JobFailed`` / ``dispatch_failed``) before any report
arrived (``report_json`` is NULL). The runner may still be alive (an accept timeout, a computer that slept),
so a report carrying the row's job id overrides a guess: a final report sets the real outcome, a progress
report makes the row active again when no other update is active (otherwise it is ignored until the final
report). A row that holds a real outcome is never changed (hello repeats the last report on every reconnect).
"""

from __future__ import annotations

import sqlite3
from typing import Any

from homemesh.common.timeutil import now_iso
from homemesh.coordinator.db.database import Row
from homemesh.coordinator.db.repositories.base import Repo, jdump, jload
from homemesh.protocol.update import FINAL_STATUSES

# The coordinator's own verdicts, which a report from the runner overrides (see the module docstring).
_GUESS = "(state IN ('abandoned', 'not_started') OR (state = 'failed' AND report_json IS NULL))"
# Rows a report may still change: active ones, and the guesses (a late report wins).
_WRITABLE = f"(active IS NOT NULL OR {_GUESS})"


def _is_guess(row: sqlite3.Row) -> bool:
    return row["state"] in ("abandoned", "not_started") or (row["state"] == "failed" and row["report_json"] is None)


def _report_run_id(report: dict[str, Any] | None) -> str | None:
    run_id = report.get("run_id") if isinstance(report, dict) else None
    return run_id if isinstance(run_id, str) else None


class ActiveUpdateExists(Exception):
    """:meth:`UpdateRepo.create_active` refused: another update is active (``existing``; None if it finished
    in the meantime). The service turns it into ``update_busy`` naming that computer."""

    def __init__(self, existing: Row | None) -> None:
        super().__init__("another update is active")
        self.existing = existing


def _decode(row: dict[str, Any] | None) -> Row | None:
    if row is None:
        return None
    row["force"] = bool(row["force"])
    row["active"] = row["active"] is not None
    row["report_json"] = jload(row["report_json"], None)
    return row


class UpdateRepo(Repo):
    async def create_active(self, *, update_id: str, node_id: str, expected_commit: str, from_commit: str | None,
                            force: bool, requested_by: str | None, requested_at: str | None = None) -> Row:
        """Insert a ``requested`` row unless any update in the mesh is active. Raises
        :class:`ActiveUpdateExists` otherwise. ``update_id`` is the ``update.apply`` job id (generated by the
        service before submitting the job)."""
        at = requested_at or now_iso()

        def _tx(conn: sqlite3.Connection) -> Row:
            existing = conn.execute("SELECT * FROM node_updates WHERE active IS NOT NULL LIMIT 1").fetchone()
            if existing is not None:
                raise ActiveUpdateExists(_decode(dict(existing)))
            conn.execute(
                "INSERT INTO node_updates(id, node_id, requested_by, requested_at, expected_commit, from_commit,"
                " force, state, active) VALUES (?,?,?,?,?,?,?,'requested',1)",
                (update_id, node_id, requested_by, at, expected_commit, from_commit, int(bool(force))))
            row = conn.execute("SELECT * FROM node_updates WHERE id=?", (update_id,)).fetchone()
            return _decode(dict(row))  # type: ignore[return-value]

        try:
            return await self.db.transaction(_tx)
        except sqlite3.IntegrityError as exc:
            existing = await self.get_active()
            if existing is None:
                raise
            raise ActiveUpdateExists(existing) from exc

    async def get(self, update_id: str) -> Row | None:
        return _decode(await self.db.fetchone("SELECT * FROM node_updates WHERE id=?", (update_id,)))

    async def get_active(self) -> Row | None:
        """The one active update in the mesh, if any."""
        return _decode(await self.db.fetchone("SELECT * FROM node_updates WHERE active IS NOT NULL LIMIT 1"))

    async def active_for_node(self, node_id: str) -> Row | None:
        return _decode(await self.db.fetchone(
            "SELECT * FROM node_updates WHERE node_id=? AND active IS NOT NULL LIMIT 1", (node_id,)))

    async def latest_for_node(self, node_id: str) -> Row | None:
        """The node's most recent update (any state), for ``GET /api/v1/nodes/{id}``."""
        return _decode(await self.db.fetchone(
            "SELECT * FROM node_updates WHERE node_id=? ORDER BY requested_at DESC, rowid DESC LIMIT 1",
            (node_id,)))

    async def latest_by_node(self) -> dict[str, Row]:
        """``node_id -> latest row`` for every node that has one (one query, for ``GET /api/v1/nodes``)."""
        rows = await self.db.fetchall(
            "SELECT u.* FROM node_updates u WHERE u.rowid = (SELECT v.rowid FROM node_updates v"
            " WHERE v.node_id = u.node_id ORDER BY v.requested_at DESC, v.rowid DESC LIMIT 1)")
        return {r["node_id"]: _decode(r) for r in rows}  # type: ignore[misc]

    async def list_for_node(self, node_id: str, limit: int = 20) -> list[Row]:
        rows = await self.db.fetchall(
            "SELECT * FROM node_updates WHERE node_id=? ORDER BY requested_at DESC, rowid DESC LIMIT ?",
            (node_id, limit))
        return [_decode(r) for r in rows]  # type: ignore[misc]

    async def set_running(self, update_id: str, run_id: str) -> bool:
        """The ``update.apply`` job completed (``{"run_id", "state": "started"}``): ``requested`` → ``running``
        and remember the run id. A row that already moved on keeps its state."""
        n = await self.db.execute(
            "UPDATE node_updates SET run_id=COALESCE(run_id, ?),"
            " state=CASE WHEN state='requested' THEN 'running' ELSE state END WHERE id=? AND " + _WRITABLE,
            (run_id, update_id))
        return n == 1

    async def update_from_report(self, update_id: str, *, phase: str, report: dict[str, Any],
                                 run_id: str | None = None, reported_at: str | None = None) -> bool:
        """A non-final report for this row (``report.job_id == update_id``): store phase, report and the
        coordinator's receive time; ``requested`` becomes ``running``. Final reports go to :meth:`finish`.

        On a guess (``not_started``, ``abandoned``, ``failed`` without a report) the runner is evidently
        alive: the row becomes ``running`` and active again, unless another update is active in the mesh
        (then nothing changes and False is returned; the final report still lands). ``run_id`` defaults to
        ``report["run_id"]``. Returns True if the row changed."""
        at = reported_at or now_iso()
        rid = run_id or _report_run_id(report)
        data = jdump(report)

        def _tx(conn: sqlite3.Connection) -> bool:
            row = conn.execute("SELECT state, active, report_json FROM node_updates WHERE id=?",
                               (update_id,)).fetchone()
            if row is None:
                return False
            if row["active"] is not None:
                conn.execute(
                    "UPDATE node_updates SET phase=?, report_json=?, last_report_at=?, run_id=COALESCE(run_id, ?),"
                    " state=CASE WHEN state='requested' THEN 'running' ELSE state END WHERE id=?",
                    (phase, data, at, rid, update_id))
                return True
            if not _is_guess(row):
                return False
            if conn.execute("SELECT 1 FROM node_updates WHERE active IS NOT NULL LIMIT 1").fetchone():
                return False
            conn.execute(
                "UPDATE node_updates SET state='running', active=1, finished_at=NULL, error_code=NULL, error=NULL,"
                " hint=NULL, phase=?, report_json=?, last_report_at=?, run_id=COALESCE(run_id, ?) WHERE id=?",
                (phase, data, at, rid, update_id))
            return True

        return await self.db.transaction(_tx)

    async def finish(self, update_id: str, *, state: str, error_code: str | None = None, error: str | None = None,
                     hint: str | None = None, report: dict[str, Any] | None = None, phase: str | None = None,
                     run_id: str | None = None, finished_at: str | None = None) -> bool:
        """End a row. Clears ``active``. Returns True if the row changed. Three uses:

        * a **final report** from the runner: ``state`` = its status, with ``report`` and ``phase`` (and
          ``run_id``, default ``report["run_id"]``). Overwrites an active row or a guess (see the module
          docstring); a row that already holds a real outcome is left alone (hello repeats the last report
          on every reconnect).
        * ``state="failed"`` **without** ``report``: the apply job failed before the runner was heard from
          (``JobFailed`` with an ``update_*`` code, ``dispatch_failed``). Applies only to an active row that
          has no report yet; once the runner reported, its reports decide (returns False). The row is a
          guess afterwards: a report for it still wins.
        * ``state="not_started"``: only ends an active row.
        """
        if state == "not_started":
            where = "active IS NOT NULL"
        elif state == "failed" and report is None:
            where = "active IS NOT NULL AND report_json IS NULL"
        elif state in FINAL_STATUSES:
            where = _WRITABLE
        else:
            raise ValueError(f"not a final update state: {state}")
        now = finished_at or now_iso()
        sets = ["state=?", "active=NULL", "finished_at=?", "error_code=?", "error=?", "hint=?",
                "run_id=COALESCE(run_id, ?)"]
        vals: list[Any] = [state, now, error_code, error, hint, run_id or _report_run_id(report)]
        if report is not None:
            sets += ["report_json=?", "last_report_at=?"]
            vals += [jdump(report), now_iso()]
        if phase is not None:
            sets.append("phase=?")
            vals.append(phase)
        n = await self.db.execute(f"UPDATE node_updates SET {', '.join(sets)} WHERE id=? AND {where}",
                                  (*vals, update_id))
        return n == 1

    async def abandon(self, update_id: str, *, error: str, hint: str | None,
                      error_code: str = "update_abandoned", finished_at: str | None = None) -> bool:
        """Owner's Dismiss (the service checks the 15-minute rule): an active row becomes ``abandoned``
        ("outcome unknown"). A late report can still overwrite it with the real outcome."""
        n = await self.db.execute(
            "UPDATE node_updates SET state='abandoned', active=NULL, finished_at=?, error_code=?, error=?, hint=?"
            " WHERE id=? AND active IS NOT NULL",
            (finished_at or now_iso(), error_code, error, hint, update_id))
        return n == 1
