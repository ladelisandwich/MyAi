# --------------------------------------------------------------------------- text hygiene (9.6)

_C0C1 = re.compile(r"[\x00-\x1f\x7f-\x9f]")
_C0C1_KEEP_NL = re.compile(r"[\x00-\x08\x0b-\x1f\x7f-\x9f]")  # keeps \t and \n (multi-line messages)
_URL_USERINFO = re.compile(r"://[^/@\s]+@")
_GH_TOKEN = re.compile(r"(?:gh[pousr]_[A-Za-z0-9_]+|github_pat_[A-Za-z0-9_]+)")


def redact(text: str) -> str:
    """Remove credentials from tool output: URL userinfo and GitHub tokens (the runner has an identical copy)."""
    return _GH_TOKEN.sub("***", _URL_USERINFO.sub("://***@", text))


def clean_line(text: str, limit: int) -> str:
    """One line of untrusted text: C0/C1 control characters removed (plain space kept), capped."""
    return _C0C1.sub("", text)[:limit]


def clean_text(text: str, limit: int) -> str:
    """Multi-line untrusted text: control characters except tab and newline removed, capped."""
    return _C0C1_KEEP_NL.sub("", text)[:limit]


def _line(limit: int, value: str) -> str:
    return clean_line(value, limit)


def _text(limit: int, value: str) -> str:
    return clean_text(value, limit)


def _take(limit: int, value: Any) -> Any:
    return value[:limit] if isinstance(value, list) else value


def _sha_or_none(value: str | None) -> str | None:
    if value is not None and not is_sha(value):
        raise ValueError("not a full lower-case hex commit id")
    return value


Code = Annotated[str, AfterValidator(partial(_line, CODE_MAX))]
