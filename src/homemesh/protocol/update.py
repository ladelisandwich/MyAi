"""Remote updater: wire schemas, file schemas shared with the worker, and the error-code table.

Everything here is **additive-only** across releases (``"v": 1``, unknown fields ignored), because the
hub, an updating worker and the runner of the previous version all read these shapes (docs/UPDATING.md,
"File contracts"). The design is in the remote-updater section of docs/UPDATING.md; the short version:

* ``update.check`` / ``update.apply`` jobs carry :class:`UpdateCheckPayload` / :class:`UpdateApplyPayload`.
  Both are ``extra="forbid"``; the apply payload carries only a full commit sha. The worker never takes a
  run id, a path or a ref name from the hub.
* ``Hello.build`` (a :class:`BuildInfo`), ``Hello.update`` and ``Heartbeat.update`` (an
  :class:`UpdateRunReport`) travel as size-capped plain dicts (see ``protocol/messages.py``); the
  coordinator parses them with these models inside ``try/except``.
* Strings that come from git, pip or npm are capped and stripped of control characters by the models, so
  a hostile commit subject can't put escape sequences into a log or the UI.

Nothing in this module raises on bad *input* to the lenient helpers (:func:`lenient_dict`,
:func:`format_update_error`): a malformed nested value must never invalidate a hello.
"""

