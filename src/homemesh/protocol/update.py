# Alternative message templates: (code, variant) -> message. The hint stays the code's hint.
UPDATE_MESSAGE_VARIANTS: dict[tuple[str, str], str] = {
    ("update_busy", "mesh"): "Another computer ({name}) is updating.",
}

UPDATE_ERROR_CODES: frozenset[str] = frozenset(UPDATE_ERRORS)
UPDATE_WARNING_CODES: frozenset[str] = frozenset(UPDATE_WARNINGS)

_DEFAULT_FIELDS: dict[str, str] = {
    "computer": "this computer",
    "source_dir": "the HomeMesh source folder",
    "log": "the update log",
    "installer_command": "run the installer again (docs/UPDATING.md)",
    "phase": "an unknown phase",
    "commit": "an unknown version",
    "short": "this version",
    "detail": "no details",
    "lines": "no output",
    "reason": "unknown reason",
}


class _Fields(dict):  # type: ignore[type-arg]
    def __missing__(self, key: str) -> str:
        return _DEFAULT_FIELDS.get(key, f"<{key}>")


def _render(template: str, fields: dict[str, Any]) -> str:
    try:
        return template.format_map(_Fields(fields))
    except Exception:
        return template


def format_update_error(code: str, /, *, variant: str | None = None, **fields: Any) -> UpdateIssue:
    """Message and hint for an error or warning ``code``, with ``fields`` filled in. Never raises.

    Placeholders the caller doesn't pass become readable defaults ("this computer", "the update log",
    ``<name>``). ``phase`` given as a phase key is shown as words ("while building the new version").
    ``None`` values count as missing. An unknown code gives a generic text that still names the code.
    """
    try:
        values = {k: v for k, v in fields.items() if v is not None and v != ""}
        phase = values.get("phase")
        if isinstance(phase, str) and phase in PHASE_LABELS:
            values["phase"] = PHASE_LABELS[phase]
        entry = UPDATE_ERRORS.get(code) or UPDATE_WARNINGS.get(code)
        if entry is None:
            message, hint = f"The update failed ({code}).", "See {log}."
        else:
            message, hint = entry
        if variant is not None:
            message = UPDATE_MESSAGE_VARIANTS.get((code, variant), message)
        return UpdateIssue(code=str(code), message=_render(message, values), hint=_render(hint, values))
    except Exception:
        return UpdateIssue(code="update_error", message="The update failed.", hint=None)


def installer_command(os_name: str | None, source_dir: str | None, *, pull: bool = False) -> str:
    """The command that updates or repairs HomeMesh by hand on a computer (shown in hints and the UI).

    ``pull=True`` first fast-forwards the checkout (updating a computer without the updater, or a target
    that needs the installer); ``pull=False`` reinstalls what the checkout holds (recovery after a failed
    rollback, where the checkout was deliberately not advanced).
    """
    if os_name == "windows":
        where = f'cd "{source_dir}"' if source_dir else "cd <HomeMesh source folder>"
        pull_step = "git pull --ff-only; " if pull else ""
        return f"{where}; {pull_step}powershell -ExecutionPolicy Bypass -File deploy\\windows\\install.ps1 -Upgrade"
    if source_dir:
        src = shlex.quote(source_dir)
        if pull:
            return f"cd {src} && git pull --ff-only && ./deploy/linux/install.sh --upgrade"
        return f"{shlex.quote(source_dir.rstrip('/') + '/deploy/linux/install.sh')} --upgrade"
    pull_step = "git pull --ff-only && " if pull else ""
    return f"cd <HomeMesh source folder> && {pull_step}./deploy/linux/install.sh --upgrade"
