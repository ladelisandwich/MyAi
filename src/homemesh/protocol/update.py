JobIdText = Annotated[str, AfterValidator(partial(_line, ID_MAX))]
Sha = Annotated[str, AfterValidator(_sha_or_none)]


def json_size(value: Any) -> int:
    """Size of ``value`` as compact UTF-8 JSON; a huge number if it can't be serialised (never raises)."""
    try:
        return len(json.dumps(value, ensure_ascii=False, separators=(",", ":"), allow_nan=False).encode("utf-8"))
    except Exception:
        return 1 << 62


def lenient_dict(value: Any, max_bytes: int) -> dict[str, Any] | None:
    """``value`` as a plain JSON object if it is a dict that serialises to at most ``max_bytes``; else None.

    Used by the ``mode="before"`` validators of ``Hello.build`` / ``Hello.update`` / ``Heartbeat.update``.
    **Never raises**: a hello with a bad ``build`` must still be accepted (otherwise the coordinator closes
    the socket with 1002 and the worker reconnects forever, unreachable for updates).
    """
    try:
        if not isinstance(value, dict) or json_size(value) > max_bytes:
            return None
        out = json.loads(json.dumps(value, ensure_ascii=False, allow_nan=False))  # str keys, plain JSON
        return out if isinstance(out, dict) else None
    except Exception:
        return None


# --------------------------------------------------------------------------- job payloads

class UpdateCheckPayload(BaseModel):
    """``update.check``: no parameters. The worker checks the branch its checkout already tracks."""

    model_config = ConfigDict(extra="forbid")


class UpdateApplyPayload(BaseModel):
    """``update.apply``: install exactly ``expected_commit`` if it is still the tip of the tracked branch.

    The runner resolves the upstream tip itself and compares it to this string; the payload is never passed
    to git. ``force`` skips draining (running jobs are stopped).
    """

    model_config = ConfigDict(extra="forbid")

    expected_commit: StrictStr
    force: StrictBool = False

    @field_validator("expected_commit")
    @classmethod
    def _full_sha(cls, v: str) -> str:
        if not is_sha(v):
            raise ValueError("expected_commit must be a full 40- or 64-character lower-case hex commit id")
        return v


class UpdateApplyResult(BaseModel):
    """``update.apply`` job result: the runner was started and accepted the run."""

    model_config = ConfigDict(extra="ignore")

    run_id: str
    state: Literal["started"] = "started"

    @field_validator("run_id")
    @classmethod
    def _run_id(cls, v: str) -> str:
        if not is_run_id(v):
            raise ValueError("invalid run id")
        return v


# --------------------------------------------------------------------------- shared shapes

class UpdateIssue(BaseModel):
    """``{code, message, hint}``: a run error, a warning, or a check error."""

    model_config = ConfigDict(extra="ignore")

    code: Code
    message: Message = ""
    hint: Hint | None = None


class UpdateProblem(UpdateIssue):
    """A finding of a check. ``blocking`` problems make ``can_update`` false."""

    blocking: bool = False


class UpdateCommit(BaseModel):
    model_config = ConfigDict(extra="ignore")

    sha: Sha
    subject: Subject = ""
    date: Timestamp | None = None


# --------------------------------------------------------------------------- Hello.build

class BuildInfo(BaseModel):
    """What this computer runs and whether it can be updated (``Hello.build``; ``record.build_info()``).

    ``update_allowed`` is the consent marker at connect time and only advisory (used for the UI hint); every
    check result carries the live value. ``source_dir`` and ``logs_dir`` let the UI build recovery commands.
    """

    model_config = ConfigDict(extra="ignore")

    v: int = 1
    version: Name
    commit: Sha | None = None
    commit_date: Timestamp | None = None
    branch: Name | None = None
    dirty: bool | None = None
    source: BuildSource = "unknown"
    reason: Text | None = None
    installed_at: Timestamp | None = None
    os: BuildOS = "other"
    can_update: bool = False
    cannot_update_reason: Text | None = None
    update_allowed: bool = False
    source_dir: PathText | None = None
    logs_dir: PathText | None = None

    def to_wire(self) -> dict[str, Any]:
        """JSON dict for ``Hello.build``, guaranteed to fit :data:`MAX_BUILD_BYTES`."""
        d = self.model_dump(mode="json")
        for key in ("reason", "cannot_update_reason"):
            if json_size(d) <= MAX_BUILD_BYTES:
                break
            if d.get(key):
                d[key] = d[key][:120]
        for key in ("reason", "cannot_update_reason", "commit_date", "installed_at", "branch", "source_dir"):
            if json_size(d) <= MAX_BUILD_BYTES:
                break
            d[key] = None
        return d


# --------------------------------------------------------------------------- check result

class UpdateCheckResult(BaseModel):
    """``checks/<run_id>.json`` written by the check runner, and the ``update.check`` job result.

    ``ok: false`` carries only ``error``. The worker sets ``allowed`` to the live consent value before
    sending. ``can_update`` is normalised here: true only when ``ok``, ``behind > 0`` and no blocking problem.
    """

    model_config = ConfigDict(extra="ignore")

    v: int = 1
    ok: bool
    checked_at: Timestamp | None = None
    allowed: bool | None = None
    installed_commit: Sha | None = None
    installed_dirty: bool | None = None
    head_commit: Sha | None = None
    branch: Name | None = None
    remote: Name | None = None
    upstream_ref: Name | None = None
    upstream_commit: Sha | None = None
    upstream_date: Timestamp | None = None
    behind: int | None = Field(default=None, ge=0)
    ahead: int | None = Field(default=None, ge=0)
    commits: Annotated[list[UpdateCommit], BeforeValidator(partial(_take, MAX_COMMITS))] = Field(
        default_factory=list)
    commits_truncated: bool = False
    web_changed: bool | None = None
    node_found: bool | None = None
    migrations: bool | None = None
    can_update: bool = False
    problems: Annotated[list[UpdateProblem], BeforeValidator(partial(_take, MAX_PROBLEMS))] = Field(
        default_factory=list)
    error: UpdateIssue | None = None

    @model_validator(mode="after")
    def _consistent(self) -> UpdateCheckResult:
        if not self.ok:
            if self.error is None:
                raise ValueError("a failed check must carry an error")
            self.can_update = False
            return self
        if self.upstream_commit is None or self.behind is None:
            raise ValueError("a successful check must report upstream_commit and behind")
        blocking = any(p.blocking for p in self.problems)
        self.can_update = bool(self.can_update and self.behind > 0 and not blocking)
        return self


# --------------------------------------------------------------------------- run report

class UpdateRunReport(BaseModel):
    """The part of ``runs/<run_id>/run.json`` the agent sends in ``Hello.update`` / ``Heartbeat.update``.

    ``model_validate(run_json)`` works directly (unknown run.json fields are ignored). ``status`` is ``None``
    while the run is in progress. ``job_id`` is ``None`` for local runs (``homemesh update``).
    """

    model_config = ConfigDict(extra="ignore")

    v: int = 1
    run_id: str
    job_id: JobIdText | None = None
    origin: UpdateOrigin
    phase: UpdatePhase
    status: FinalStatus | None = None
    from_commit: Sha | None = None
    to_commit: Sha | None = None
    started_at: Timestamp
    updated_at: Timestamp
    finished_at: Timestamp | None = None
    error: UpdateIssue | None = None
    warnings: Annotated[list[UpdateIssue], BeforeValidator(partial(_take, MAX_WARNINGS))] = Field(
        default_factory=list)
    log: PathText | None = None

    @field_validator("run_id")
    @classmethod
    def _run_id(cls, v: str) -> str:
        if not is_run_id(v):
            raise ValueError("invalid run id")
        return v

    @property
    def final(self) -> bool:
        return self.status is not None

    @property
    def restarting(self) -> bool:
        """HomeMesh on that computer is stopping or restarting for this run right now."""
        return self.status is None and self.phase in RESTART_PHASES

    def to_wire(self) -> dict[str, Any]:
        """JSON dict for ``Hello.update`` / ``Heartbeat.update``, guaranteed to fit :data:`MAX_REPORT_BYTES`.

        Trims (in order) warnings from the end, then the error text, so the outcome itself always arrives.
        """
        d = self.model_dump(mode="json")
        while json_size(d) > MAX_REPORT_BYTES and d["warnings"]:
            d["warnings"].pop()
        if json_size(d) > MAX_REPORT_BYTES and d.get("error"):
            d["error"]["message"] = d["error"]["message"][:200]
            if d["error"].get("hint"):
                d["error"]["hint"] = d["error"]["hint"][:200]
        if json_size(d) > MAX_REPORT_BYTES:
            d["log"] = None
        return d


def parse_build(value: Any) -> BuildInfo | None:
    """Coordinator side: ``Hello.build`` → :class:`BuildInfo`, or None when absent/invalid (never raises)."""
    if not isinstance(value, dict):
        return None
    try:
        return BuildInfo.model_validate(value)
    except Exception:
        return None


def parse_report(value: Any) -> UpdateRunReport | None:
    """Coordinator side: ``Hello.update`` / ``Heartbeat.update`` → report, or None (never raises)."""
    if not isinstance(value, dict):
        return None
    try:
        return UpdateRunReport.model_validate(value)
    except Exception:
        return None


