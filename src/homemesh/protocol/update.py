# --------------------------------------------------------------------------- patterns
# Documented with anchors (for TypeScript and docs); Python code uses re.fullmatch with the bodies below,
# because Python's "$" also matches before a trailing newline.

SHA_PATTERN = r"^[0-9a-f]{40}([0-9a-f]{24})?$"
"""A full SHA-1 (40) or SHA-256 (64) commit id, lower-case hex. Never a short sha, ref or revision expression."""

RUN_ID_PATTERN = r"^u[0-9]{14}-[0-9a-f]{8}$"
"""``u`` + UTC ``yyyymmddHHMMSS`` + ``-`` + 8 hex. Generated by the worker / CLI (``files.new_run_id``),
safe for file names and systemd unit names. ASCII digits only (Python's ``\\d`` would accept others)."""

VENV_ID_PATTERN = r"^([0-9a-f]{12}|nogit|legacy)-[0-9]{14}$"
"""Name of a directory under ``<prefix>/venvs/``; only such names are ever pruned."""

REF_NAME_PATTERN = r"^[A-Za-z0-9._/-]+$"
"""Remote and branch names the runner accepts (and they must not start with ``-``)."""

_SHA_RE = re.compile(r"[0-9a-f]{40}(?:[0-9a-f]{24})?")
_RUN_ID_RE = re.compile(r"u[0-9]{14}-[0-9a-f]{8}")
_VENV_ID_RE = re.compile(r"(?:[0-9a-f]{12}|nogit|legacy)-[0-9]{14}")
_REF_NAME_RE = re.compile(r"[A-Za-z0-9._/-]+")


def is_sha(value: object) -> bool:
    return isinstance(value, str) and _SHA_RE.fullmatch(value) is not None


def is_run_id(value: object) -> bool:
    return isinstance(value, str) and _RUN_ID_RE.fullmatch(value) is not None


def is_venv_id(value: object) -> bool:
    return isinstance(value, str) and _VENV_ID_RE.fullmatch(value) is not None


def is_ref_name(value: object) -> bool:
    return isinstance(value, str) and not value.startswith("-") and _REF_NAME_RE.fullmatch(value) is not None


def short_sha(sha: str | None) -> str | None:
    """The 7-character form shown to people (``a38a3fa``). ``None`` stays ``None``."""
    return sha[:7] if isinstance(sha, str) and sha else None


